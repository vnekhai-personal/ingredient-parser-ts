// Generate the lazy foundation-foods runtime modules from the vendored upstream data files
// (write-once, provenance in docs/MODELS.md), Node only — a clean checkout builds without
// Python or the upstream clone (docs/VERIFICATION.md):
//   models/upstream/ingredient_embeddings.35d.glove.txt.gz -> src/en/data/glove.en.ts
//   models/upstream/fdc_ingredients.csv.gz                  -> src/en/data/fdc.en.ts
// Output is byte-identical to training/gen-ff-assets.py (the Python cross-check): GloVe values
// are parsed like `float(v)` then float32 (Number -> fround), tokens split on Python `str.split()`
// whitespace; the CSV is parsed with csv-module semantics (RFC 4180 quoting, embedded newlines).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';

const ROOT = new URL('../', import.meta.url);
const GLOVE_GZ = new URL('models/upstream/ingredient_embeddings.35d.glove.txt.gz', ROOT);
const FDC_GZ = new URL('models/upstream/fdc_ingredients.csv.gz', ROOT);
const OUT_DIR = new URL('src/en/data/', ROOT);
const PIN = 'ffd6ae3c6efb9925c40fc9b4454d77b40469ef91';
// Python str.split() / rstrip() whitespace (str.isspace()).
const PY_WS_SRC = '[\\t\\n\\x0b\\x0c\\r\\x1c-\\x1f \\x85\\xa0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]+';
const PY_WS = new RegExp(PY_WS_SRC, 'u');
const PY_RSTRIP = new RegExp(PY_WS_SRC + '$', 'u');
const sha = (buf) => createHash('sha256').update(buf).digest('hex');

function upToDate(out, marker) {
  return existsSync(out) && readFileSync(out, 'utf8').includes(marker);
}

// ---- GloVe ----
const gloveGz = readFileSync(GLOVE_GZ);
const gloveSha = sha(gloveGz);
const gloveMarker = `// sha256(models/upstream/ingredient_embeddings.35d.glove.txt.gz) = ${gloveSha} (format 2)`;
const gloveOut = new URL('glove.en.ts', OUT_DIR);
mkdirSync(OUT_DIR, { recursive: true });
if (upToDate(gloveOut, gloveMarker)) {
  console.log('src/en/data/glove.en.ts up to date');
} else {
  const text = gunzipSync(gloveGz).toString('utf8');
  const lines = text.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  const header = lines[0].replace(PY_RSTRIP, '');
  const [vocabSize, dim] = header.split(PY_WS).map(Number);
  const vocab = [];
  const vectors = new Float32Array((lines.length - 1) * dim);
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].replace(PY_RSTRIP, '').split(PY_WS);
    vocab.push(parts[0]);
    if (parts.length - 1 !== dim) throw new Error(`row ${i}: ${parts.length - 1} values, expected ${dim}`);
    for (let j = 0; j < dim; j++) vectors[(i - 1) * dim + j] = Number(parts[1 + j]);
  }
  // Explicit little-endian serialisation (host order is not assumed).
  const bytes = new Uint8Array(vectors.length * 4);
  const view = new DataView(bytes.buffer);
  for (let i = 0; i < vectors.length; i++) view.setFloat32(i * 4, vectors[i], true);
  const b64 = Buffer.from(bytes).toString('base64');
  writeFileSync(
    gloveOut,
    `// GENERATED by training/extract-ff-assets.mjs from models/upstream/ingredient_embeddings.35d.glove.txt.gz (upstream @ ${PIN}). Do not edit.\n` +
      `${gloveMarker}\n` +
      `/** sha256 of the gz input, checked against data/ffcache.en.ts by preload_foundation_foods(). */\nexport const SHA256 = '${gloveSha}';\n` +
      `/** Header value (upstream \`vocab_size\`); VOCAB.length is the real row count. */\nexport const VOCAB_SIZE = ${vocabSize};\nexport const DIMENSION = ${dim};\n` +
      `export const VOCAB: readonly string[] = ${JSON.stringify(vocab)};\n` +
      `/** ${vocab.length} x ${dim} float32, little-endian, row-major, base64. */\nexport const VECTORS_B64: string = ${JSON.stringify(b64)};\n`,
  );
  console.log(`wrote src/en/data/glove.en.ts (${vocab.length} rows (header ${vocabSize}) x ${dim})`);
}

// ---- FDC csv (Python csv module, default dialect) ----
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i += 1;
        continue;
      }
      field += c;
      i += 1;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (c === ',') {
      row.push(field);
      field = '';
      i += 1;
      continue;
    }
    if (c === '\r') {
      i += 1;
      continue;
    }
    if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
      i += 1;
      continue;
    }
    field += c;
    i += 1;
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}
const fdcGz = readFileSync(FDC_GZ);
const fdcSha = sha(fdcGz);
const fdcMarker = `// sha256(models/upstream/fdc_ingredients.csv.gz) = ${fdcSha} (format 2)`;
const fdcOut = new URL('fdc.en.ts', OUT_DIR);
if (upToDate(fdcOut, fdcMarker)) {
  console.log('src/en/data/fdc.en.ts up to date');
} else {
  const rows = parseCsv(gunzipSync(fdcGz).toString('utf8'));
  const header = rows[0];
  const idx = Object.fromEntries(header.map((h, k) => [h, k]));
  const out = rows
    .slice(1)
    .filter((r) => r.length > 1)
    .map((r) => ({
      fdc_id: Number(r[idx.fdc_id]),
      data_type: r[idx.data_type],
      description: r[idx.description],
      category: r[idx.category],
    }));
  writeFileSync(
    fdcOut,
    `// GENERATED by training/extract-ff-assets.mjs from models/upstream/fdc_ingredients.csv.gz (upstream @ ${PIN}). Do not edit.\n` +
      `${fdcMarker}\n` +
      `/** sha256 of the gz input, checked against data/ffcache.en.ts by preload_foundation_foods(). */\nexport const SHA256 = '${fdcSha}';\n` +
      `export interface FDCRow { fdc_id: number; data_type: string; description: string; category: string }\n` +
      `export const FDC_ROWS: readonly FDCRow[] = ${JSON.stringify(out)};\n`,
  );
  console.log(`wrote src/en/data/fdc.en.ts (${out.length} rows)`);
}
